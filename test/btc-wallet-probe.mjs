/**
 * BTC WALLET PROBE — the internal bitcoin leg, end to end.
 * ---------------------------------------------------------------------------
 * The P2P funnel used to end at a paste box: buy rial→BTC on the market tab,
 * then go to TrustWallet to receive it, and the follow-up swap — our actual
 * revenue — happened there too. The internal BIP-84 wallet closes that loop:
 * same seed, same backup, m/84'/0'/0'/0/x.
 *
 * This probe proves the whole leg against SPEC VECTORS, not against itself:
 *
 *   1. DERIVATION — addressAt(0)/(1) on the official BIP-84 test vector
 *      (abandon…about) reproduce the BIP's own first receive addresses
 *      byte-for-byte. The vectors are copied from the BIP-84 text, not
 *      generated by the code under test.
 *   2. ENCODING — decode(encode(x))===x, and the hash160 the BIP prints for
 *      index 0 encodes to the BIP's address. (The full BIP-173/350 valid/
 *      invalid table stays in test/p2p-market-probe.mjs — reused, not
 *      duplicated; these are the encoding facts only that table cannot
 *      express.)
 *   3. TRANSACTION SIGNING — the canonical BIP-143 native-P2WPKH example:
 *      the sighash digest AND the DER signature bytes equal the values the
 *      BIP itself prints, and our serializer round-trips the BIP's signed
 *      transaction hex byte-identically. If either drifts, mainnet money
 *      would be at stake — this is the one assertion that cannot be loose.
 *   4. TX BUILDING — all-UTXO selection, OP_RETURN memo carried verbatim,
 *      integer sats, and the failure modes (dust payee, bad payee, memo
 *      >80B, insufficient funds, key mismatch) fail CLOSED with named codes.
 *   5. THE PROXY — real HTTP through server/app.js with the Esplora
 *      upstream stubbed: the allow-list (mainnet checksum before ANY
 *      upstream call), integer sats out, confirmed-only UTXOs, honest
 *      429/503/502 (never 500), and every outgoing call pinned to
 *      BTC_API_BASE. No secret ever travels — there is none in this module's
 *      vocabulary to leak.
 *
 * Standalone:
 *   node test/btc-wallet-probe.mjs
 * The shared runner (test/run.mjs) imports the default export of rows.
 */

import { pathToFileURL } from 'node:url';

const rows = [];
const t = (name, ok) => rows.push([name, Boolean(ok)]);

process.env.RATE_LIMIT = process.env.RATE_LIMIT || '100000';

/* The probe pins the upstream base BEFORE importing the server so the env
   override is proven, not assumed. */
const PROBE_BASE = 'https://btc-probe.example/api';
process.env.BTC_API_BASE = PROBE_BASE;

const realFetch = globalThis.fetch;

/* ---------------------------------------------------------------------------
 * PART A — pure modules (same bytes the browser bundle runs)
 * ------------------------------------------------------------------------- */

const {
  btcAddressInfo,
  btcAddressScript,
  encodeSegwitAddress,
  sha256
} = await import('../src/lib/btcAddress.js');
const { addressAt, btcAddressForSigner, btcSpendFromSigner, bip84Path } = await import('../src/lib/btcWallet.js');
const {
  parseBitcoinTx,
  p2wpkhSighash,
  p2wpkhScriptCode,
  signP2wpkhInput,
  serializeTx,
  txidOf,
  buildP2wpkhTx,
  opReturnScript,
  hexToBytes,
  bytesToHex
} = await import('../src/lib/btcTx.js');

/* ── 1. derivation: the official BIP-84 vector, copied from the BIP text ── */
const BIP84_MNEMONIC = 'abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon about';
const BIP84_RECEIVE_0 = 'bc1qcr8te4kr609gcawutmrza0j4xv80jy8z306fyu';
const BIP84_RECEIVE_1 = 'bc1qnjg0jd8228aq7egyzacy8cys3knf9xvrerkf9g';
const BIP84_PUBKEY_0 = '0x0330d54fd0dd420a6e5f8d3624f5f3482cae350f79d5f0753bf5beef9c2d91af3c';

{
  const zero = await addressAt(0, BIP84_MNEMONIC);
  const one = await addressAt(1, BIP84_MNEMONIC);
  t('BIP-84: first receive address matches the spec vector', zero.address === BIP84_RECEIVE_0);
  t('BIP-84: second receive address matches the spec vector', one.address === BIP84_RECEIVE_1);
  t('BIP-84: compressed pubkey matches the spec vector', zero.publicKey.toLowerCase() === BIP84_PUBKEY_0);
  t('BIP-84: path is m/84\'/0\'/0\'/0/index', bip84Path(0) === 'm/84\'/0\'/0\'/0/0' && one.path === 'm/84\'/0\'/0\'/0/1');

  let threw = false;
  try { await addressAt(0, 'not a mnemonic at all'); } catch { threw = true; }
  t('BIP-84: a bogus mnemonic is refused (BAD_MNEMONIC)', threw);
  threw = false;
  try { await addressAt(-1, BIP84_MNEMONIC); } catch { threw = true; }
  t('BIP-84: a negative index is refused (BAD_INDEX)', threw);
}

/* ── 2. encoding: decode(encode(x))===x on the BIP's own hash160 ────────── */
{
  /* 1d0f… is the hash160 the BIP-143 example itself pays to — the encoder is
     exercised on spec data, not on our own output. */
  const { btcAddressProgram } = await import('../src/lib/btcAddress.js');
  const program = hexToBytes('1d0f172a0ecb48aee1be1f2687d2963ae33f71a1');
  const enc = encodeSegwitAddress('bc', 0, program);
  const back = btcAddressProgram(enc);
  t('encode: v0 program encodes and decodes back to itself',
    Boolean(back) && back.version === 0 && bytesToHex(back.program) === bytesToHex(program));
  t('encode: testnet HRP is refused by the mainnet validator', btcAddressInfo(enc.replace(/^bc/, 'tb')).valid === false);

  /* the payment scripts a send needs, derived from the SAME decode */
  t('script: p2wpkh output script is 0014<hash160>',
    bytesToHex(btcAddressScript(BIP84_RECEIVE_0)) === '0014c0cebcd6c3d3ca8c75dc5ec62ebe55330ef910e2');
  t('script: p2pkh output script is 76a914…88ac',
    bytesToHex(btcAddressScript('1BgGZ9tcN4rm9KBzDn7KprQz87SZ26SAMH')).startsWith('76a914') &&
    bytesToHex(btcAddressScript('1BgGZ9tcN4rm9KBzDn7KprQz87SZ26SAMH')).endsWith('88ac'));
  t('script: p2sh output script is a914…87',
    bytesToHex(btcAddressScript('3J98t1WpEZ73CNmQviecrnyiWrnqRhWNLy')).startsWith('a914'));
  t('script: a testnet address yields NO script', btcAddressScript('tb1qrp33g0q5c5txsp9arysrx4k6zdkfs4nce4xj0gdcccefvpys9r0zlzrpc9') === null);
  t('script: garbage yields NO script', btcAddressScript('hello world') === null);
}

/* ── 3. the canonical BIP-143 native-P2WPKH example ──────────────────────── */
const BIP143 = {
  unsigned: '0100000002fff7f7881a8099afa6940d42d1e7f6362bec38171ea3edf433541db4e4ad969f0000000000eeffffffef51e1b804cc89d182d279655c3aa89e815b1b309fe287d9b2b55d57b90ec68a0100000000ffffffff02202cb206000000001976a9148280b37df378db99f66f85c95a783a76ac7a6d5988ac9093510d000000001976a9143bde42dbee7e4dbe6a21b2d50ce2f0167faa815988ac11000000',
  signed: '01000000000102fff7f7881a8099afa6940d42d1e7f6362bec38171ea3edf433541db4e4ad969f00000000494830450221008b9d1dc26ba6a9cb62127b02742fa9d754cd3bebf337f7a55d114c8e5cdd30be022040529b194ba3f9281a99f2b1c0a19c0489bc22ede944ccf4ecbab4cc618ef3ed01eeffffffef51e1b804cc89d182d279655c3aa89e815b1b309fe287d9b2b55d57b90ec68a0100000000ffffffff02202cb206000000001976a9148280b37df378db99f66f85c95a783a76ac7a6d5988ac9093510d000000001976a9143bde42dbee7e4dbe6a21b2d50ce2f0167faa815988ac000247304402203609e17b84f6a7d30c80bfa610b5b4542f32a8a0d5447a12fb1366d7f01cc44a0220573a954c4518331561406f90300e8f3358f51928d43c212a8caed02de67eebee0121025476c2e83188368da1ff3e292e7acafcdb3566bb0ad253f62fc70f07aeee635711000000',
  privKey: '0x619c335025c7f4012e556c2a58b2506e30b8511b53ade95ea316fd8c3286feb9',
  pubkeyHash: '1d0f172a0ecb48aee1be1f2687d2963ae33f71a1',
  amount: 600000000,
  sigHash: 'c37af31116d1b27caf68aae9e3ac82f1477929014d5b917657d0eb49478cb670',
  signature: '304402203609e17b84f6a7d30c80bfa610b5b4542f32a8a0d5447a12fb1366d7f01cc44a0220573a954c4518331561406f90300e8f3358f51928d43c212a8caed02de67eebee01',
  txid: 'e8151a2af31c368a35053ddd4bdb285a8595c769a3ad83e0fa02314a602d4609'
};

{
  const tx = parseBitcoinTx(BIP143.unsigned);
  t('BIP-143: the unsigned fixture parses (2 in / 2 out / locktime 17)',
    tx && tx.inputs.length === 2 && tx.outputs.length === 2 && tx.locktime === 17);

  const digest = p2wpkhSighash(tx, 1, p2wpkhScriptCode(hexToBytes(BIP143.pubkeyHash)), BIP143.amount, 1);
  t('BIP-143: the sighash digest equals the value printed in the BIP', bytesToHex(digest) === BIP143.sigHash);

  const sig = await signP2wpkhInput(tx, 1, BIP143.amount, BIP143.privKey, hexToBytes(BIP143.pubkeyHash), 1);
  t('BIP-143: the DER signature bytes equal the BIP\'s own signature', bytesToHex(sig) === BIP143.signature);

  const signed = parseBitcoinTx(BIP143.signed);
  t('BIP-143: our serializer round-trips the BIP signed tx byte-identically',
    bytesToHex(serializeTx(signed, { witness: true })) === BIP143.signed);
  t('BIP-143: the witness we compute for input 1 is the BIP\'s witness',
    bytesToHex(signed.inputs[1].witness[0]) === BIP143.signature);
  t('BIP-143: txid of the signed fixture matches', txidOf(signed) === BIP143.txid);
}

/* ── 4. building real sends on the BIP-84 keys ───────────────────────────── */
{
  const zero = await addressAt(0, BIP84_MNEMONIC);
  const one = await addressAt(1, BIP84_MNEMONIC);
  const THOR_MEMO = 'SWAP:BTC.BTC/BSC.BTCB-1DE:bc1qcr8te4kr609gcawutmrza0j4xv80jy8z306fyu';

  const built = await buildP2wpkhTx({
    utxos: [
      { txid: 'a'.repeat(64), vout: 0, value: 100000 },
      { txid: 'b'.repeat(64), vout: 1, value: 50000 }
    ],
    payees: [{ address: one.address, valueSats: 40000 }],
    memo: THOR_MEMO.slice(0, 80), /* ≤80 bytes: the OP_RETURN cap a memo must fit */
    changeAddress: zero.address,
    feeRateSatVb: 3,
    privateKey: (await btcSpendFromSigner({ getAddress: async () => '0x1', mnemonic: { phrase: BIP84_MNEMONIC } }, { index: 0 })).privateKey
  });

  const rp = parseBitcoinTx(built.txHex);
  t('build: the signed tx reparses with the payee, memo and change outputs',
    Boolean(rp) && rp.outputs.length === 3);
  const memoOut = rp.outputs.map((o) => o.script).find((s) => s[0] === 0x6a);
  t('build: the OP_RETURN carries the memo string verbatim',
    Boolean(memoOut) && new TextDecoder().decode(memoOut.slice(2)) === THOR_MEMO.slice(0, 80));
  t('build: money fields are integer sats',
    rp.outputs.every((o) => Number.isInteger(o.value)) && Number.isInteger(built.feeSats));
  t('build: the txid is self-consistent with the stripped serialization', txidOf(rp) === built.txid);
  t('build: the result carries no private key material', !/privateKey|mnemonic/i.test(JSON.stringify(built)));

  const mustThrow = async (label, p) => {
    let threw = false;
    try { await p; } catch { threw = true; }
    t(`build: ${label} fails closed`, threw);
  };
  const spend0 = await btcSpendFromSigner({ getAddress: async () => '0x1', mnemonic: { phrase: BIP84_MNEMONIC } }, { index: 0 });
  await mustThrow('a dust payee',
    buildP2wpkhTx({ utxos: [{ txid: 'c'.repeat(64), vout: 0, value: 100000 }], payees: [{ address: one.address, valueSats: 100 }], changeAddress: zero.address, feeRateSatVb: 3, privateKey: spend0.privateKey }));
  await mustThrow('an invalid (testnet) payee',
    buildP2wpkhTx({ utxos: [{ txid: 'c'.repeat(64), vout: 0, value: 100000 }], payees: [{ address: 'tb1qrp33g0q5c5txsp9arysrx4k6zdkfs4nce4xj0gdcccefvpys9r0zlzrpc9', valueSats: 40000 }], changeAddress: zero.address, feeRateSatVb: 3, privateKey: spend0.privateKey }));
  await mustThrow('a >80-byte memo',
    buildP2wpkhTx({ utxos: [{ txid: 'c'.repeat(64), vout: 0, value: 100000 }], payees: [{ address: one.address, valueSats: 40000 }], memo: 'x'.repeat(81), changeAddress: zero.address, feeRateSatVb: 3, privateKey: spend0.privateKey }));
  await mustThrow('insufficient funds',
    buildP2wpkhTx({ utxos: [{ txid: 'c'.repeat(64), vout: 0, value: 41000 }], payees: [{ address: one.address, valueSats: 40000 }], changeAddress: zero.address, feeRateSatVb: 10, privateKey: spend0.privateKey }));
  await mustThrow('a key that does not match the funded hash',
    buildP2wpkhTx({ utxos: [{ txid: 'c'.repeat(64), vout: 0, value: 100000 }], payees: [{ address: one.address, valueSats: 40000 }], changeAddress: zero.address, feeRateSatVb: 3, privateKey: spend0.privateKey, pubkeyHash: hexToBytes('751e76e8199196d454941c45d1b3a323f1433bd6') }));

  /* The zero law's door: an injected wallet (no mnemonic) gets nothing. */
  const injected = await btcAddressForSigner({ getAddress: async () => '0x2' }, { index: 0 });
  const injectedSpend = await btcSpendFromSigner({ getAddress: async () => '0x2', mnemonic: {} }, { index: 0 });
  t('zero law: an injected wallet has no internal BTC address', injected === null);
  t('zero law: an injected wallet gets no spending key', injectedSpend === null);
}

/* ---------------------------------------------------------------------------
 * PART B — the proxy, over real HTTP with the upstream stubbed
 * ------------------------------------------------------------------------- */

const VALID = BIP84_RECEIVE_0; /* passes the real mainnet checksum */
const TESTNET = 'tb1qrp33g0q5c5txsp9arysrx4k6zdkfs4nce4xj0gdcccefvpys9r0zlzrpc9';

const weather = {
  mode: 'ok',
  calls: [],
  addressInfoBody: null
};

const json = (status, body) => new Response(JSON.stringify(body), {
  status,
  headers: { 'content-type': 'application/json' }
});

function installUpstreamStub() {
  globalThis.fetch = async (url, init) => {
    const u = String(url);
    /* everything EXCEPT our own test server must be the pinned upstream */
    if (u.startsWith('http://127.0.0.1')) return realFetch(url, init);

    weather.calls.push({ url: u, method: init?.method ?? 'GET' });
    if (!u.startsWith(PROBE_BASE)) {
      throw new Error(`EGRESS VIOLATION: ${u}`);
    }

    if (weather.mode === 'down-429') return json(429, { error: 'rate limited' });
    if (weather.mode === 'down-503') return new Response('maintenance', { status: 503 });
    if (weather.mode === 'unreachable') throw new Error('dns is fine, the box is gone');

    if (u.includes('/address/') && u.endsWith('/utxos')) {
      return json(200, [
        { txid: 'f'.repeat(64), vout: 0, value: 95000, status: { confirmed: true, block_height: 800000 } },
        { txid: 'e'.repeat(64), vout: 1, value: 5000, status: { confirmed: false } } /* mempool — NOT spendable */
      ]);
    }
    if (u.includes('/address/')) {
      return json(200, {
        address: VALID,
        chain_stats: { funded_txo_sum: 95000, spent_txo_sum: 0 },
        mempool_stats: { funded_txo_sum: 5000, spent_txo_sum: 0 }
      });
    }
    if (u.includes('/fees')) {
      return json(200, { fastestFee: 12, halfHourFee: 8, hourFee: 5, minimumFee: 1 });
    }
    if (u.includes('/tx') && (init?.method === 'POST')) {
      return new Response('ab'.repeat(32), { status: 200 }); /* the txid as text */
    }
    return json(404, {});
  };
}

let server = null;
try {
  installUpstreamStub();
  const { default: app } = await import('../server/app.js');
  server = await new Promise((resolve) => {
    const s = app.listen(0, '127.0.0.1', () => resolve(s));
  });
  const base = `http://127.0.0.1:${server.address().port}`;

  /* ── the allow-list gates BEFORE any upstream call ── */
  {
    weather.calls.length = 0;
    const res = await fetch(`${base}/api/btc/address/${TESTNET}`);
    const body = await res.json();
    t('proxy: a testnet address is 400 BAD_ADDRESS', res.status === 400 && body.error === 'BAD_ADDRESS');
    t('proxy: ...and no upstream call was made for it', weather.calls.length === 0);

    const res2 = await fetch(`${base}/api/btc/address/notanaddress`);
    t('proxy: garbage is 400 too', res2.status === 400);
    t('proxy: still zero upstream calls', weather.calls.length === 0);
  }

  /* ── honest address facts: integer sats, confirmed-only UTXOs ── */
  {
    weather.calls.length = 0;
    const res = await fetch(`${base}/api/btc/address/${VALID}`);
    const body = await res.json();
    t('proxy: a valid mainnet address answers 200', res.status === 200);
    t('proxy: confirmed balance is integer sats', body.confirmedSats === 95000 && Number.isInteger(body.confirmedSats));
    t('proxy: unconfirmed is reported separately, not spendable', body.unconfirmedSats === 5000);
    t('proxy: only CONFIRMED utxos are returned', body.utxos.length === 1 && body.utxos[0].value === 95000);
    t('proxy: the call went to the pinned BTC_API_BASE', weather.calls.every((c) => c.url.startsWith(PROBE_BASE)));
    t('proxy: no secret-looking material in any upstream path',
      weather.calls.every((c) => !/mnemonic|phrase|private|password|seed/i.test(c.url)));
  }

  /* ── fee table mapped to the sheet's three words ── */
  {
    const res = await fetch(`${base}/api/btc/fees`);
    const body = await res.json();
    t('proxy: fees answer fast/normal/slow in sat/vB',
      res.status === 200 && body.satPerVb.fast === 12 && body.satPerVb.normal === 8 && body.satPerVb.slow === 5);
  }

  /* ── broadcast: real hex relayed, junk refused, never echoed ── */
  {
    weather.calls.length = 0;
    const goodHex = '01'.repeat(50);
    const res = await fetch(`${base}/api/btc/tx`, {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({ rawTx: goodHex })
    });
    const body = await res.json();
    t('proxy: a signed tx relays and reports the txid', res.status === 200 && body.broadcast === true && body.txid === 'ab'.repeat(32));
    t('proxy: the relay used POST to the pinned upstream',
      weather.calls.some((c) => c.method === 'POST' && c.url === `${PROBE_BASE}/tx`));

    const resJunk = await fetch(`${base}/api/btc/tx`, {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({ rawTx: 'zzzz-not-hex' })
    });
    t('proxy: non-hex broadcast is 400 BAD_TX_HEX', resJunk.status === 400 && (await resJunk.json()).error === 'BAD_TX_HEX');

    const resEmpty = await fetch(`${base}/api/btc/tx`, {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({})
    });
    t('proxy: an empty broadcast body is 400, not 500', resEmpty.status === 400);
  }

  /* ── honest upstream weather: 429 stays 429, 503 stays 503, never 500 ──
     Each mode uses a FRESH address (its own cache key) so the TTL cache
     cannot answer for the stubbed upstream. */
  const weatherAddrs = [await addressAt(2, BIP84_MNEMONIC), await addressAt(3, BIP84_MNEMONIC), await addressAt(4, BIP84_MNEMONIC)];
  for (const [i, [mode, wantStatus, wantCode]] of [
    ['down-429', 429, 'UPSTREAM_RATE_LIMIT'],
    ['down-503', 503, 'UPSTREAM_UNAVAILABLE'],
    ['unreachable', 502, 'UPSTREAM_FAILED']
  ].entries()) {
    weather.mode = mode;
    weather.calls.length = 0;
    const res = await fetch(`${base}/api/btc/address/${weatherAddrs[i].address}`);
    const body = await res.json();
    t(`proxy: upstream ${mode} answers ${wantStatus} ${wantCode}`, res.status === wantStatus && body.error === wantCode);
    t(`proxy: upstream ${mode} never becomes a 500`, res.status !== 500);
    t(`proxy: upstream ${mode} really was called (cache did not mask it)`, weather.calls.length > 0);
  }
  weather.mode = 'ok';

  /* ── status is honest (unknown before traffic, ok after) ── */
  {
    const res = await fetch(`${base}/api/btc/status`);
    const body = await res.json();
    t('proxy: status names the pinned upstream and stays honest', res.status === 200 && body.upstream === PROBE_BASE);
  }
} finally {
  if (server) server.close();
  globalThis.fetch = realFetch;
  delete process.env.BTC_API_BASE;
}

export default rows;

/* Standalone: print the table, exit non-zero on failure. */
if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  for (const [name, ok] of rows) {
    if (!ok) process.exitCode = 1;
    console.log(`  ${ok ? '✓' : '✗'} ${name}`);
  }
  console.log(`\n${rows.filter((r) => r[1]).length}/${rows.length} passed`);
}
