/**
 * THE APP'S OWN NOTIFICATION TONE — probe (no device, no network).
 * ---------------------------------------------------------------------------
 * «نوتیفیکیشن اپلیکیشن وقتی میاد روی صفحه اندروید که از بالا به پایین میاد یک
 * آهنگ نوتیفیکیشن بزنه که خاص باشد.»
 *
 * The failure this exists to prevent is quiet and permanent: a notification
 * that arrives with the DEVICE chime looks like it works. Nothing throws,
 * nothing logs, the shade opens, the text is right — and the one property that
 * was asked for is simply absent. Worse, on Android 8+ the sound belongs to the
 * channel and a channel's sound CANNOT BE CHANGED after it exists, so the
 * mistake survives every update until somebody edits the channel id.
 *
 * So every link of the chain is asserted here, because a chain with one missing
 * link is silent:
 *
 *   1. the tone exists, is real PCM, and is not silence;
 *   2. it is REPRODUCIBLE — regenerating it produces the same bytes, which is
 *      the only honest way a binary can live in this repo;
 *   3. the channels are created in native code with that tone on them, at the
 *      importance that makes a notification drop in from the top of the screen
 *      (that is the "از بالا میاد" part — IMPORTANCE_HIGH, not DEFAULT);
 *   4. FCM resolves to those channels, by manifest default and by message;
 *   5. the local-notification path names the same channel and the same tone;
 *   6. the server sends the tone's name, never the string 'default'.
 */
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';

const root = new URL('..', import.meta.url);
const read = (p) => readFileSync(new URL(p, root), 'utf8');
const bytes = (p) => readFileSync(new URL(p, root));

let step = 0;
const ok = (name, condition) => {
  step += 1;
  assert.ok(condition, `#${step} ${name}`);
};

const SOUND = 'android/app/src/main/res/raw/fbt_notification.wav';

/* -------------------------------------------------------------------------- */
/* 1. the tone itself                                                          */
/* -------------------------------------------------------------------------- */
{
  ok('the notification tone ships in res/raw', existsSync(new URL(SOUND, root)));

  const buf = bytes(SOUND);
  ok('it is a RIFF/WAVE file', buf.toString('ascii', 0, 4) === 'RIFF' && buf.toString('ascii', 8, 12) === 'WAVE');
  ok('it is uncompressed PCM, so no OEM decoder can refuse it', buf.readUInt16LE(20) === 1);
  ok('it is mono — a notification is one speaker', buf.readUInt16LE(22) === 1);
  ok('it is 16-bit', buf.readUInt16LE(34) === 16);

  const rate = buf.readUInt32LE(24);
  const dataBytes = buf.readUInt32LE(40);
  const seconds = dataBytes / (rate * 2);
  ok('it samples at a rate every phone plays', rate === 44100);
  /* Long enough to be a melody, short enough not to be an interruption: the
     system kills a notification sound at ~5s and a ringtone-length loop would
     be an imposition on everyone within earshot. */
  ok('it lasts between half a second and three seconds', seconds > 0.5 && seconds < 3);

  /* Not silence, and not clipping: both are failures a file-level check can
     catch and an eyeball cannot. */
  let peak = 0;
  let energy = 0;
  for (let i = 0; i < dataBytes; i += 2) {
    const v = Math.abs(buf.readInt16LE(44 + i)) / 32768;
    peak = Math.max(peak, v);
    energy += v * v;
  }
  const rms = Math.sqrt(energy / (dataBytes / 2));
  ok('it is not silence', rms > 0.01);
  ok('it is loud enough to hear on a phone in a pocket', peak > 0.5);
  ok('and it does not clip', peak <= 1);

  ok('it is small enough to ship in the APK', statSync(new URL(SOUND, root)).size < 400 * 1024);
}

/* -------------------------------------------------------------------------- */
/* 2. it can be regenerated byte-for-byte                                      */
/* -------------------------------------------------------------------------- */
{
  const before = createHash('sha256').update(bytes(SOUND)).digest('hex');
  execFileSync(process.execPath, ['scripts/gen-notification-sound.mjs'], { cwd: root.pathname, stdio: 'pipe' });
  const after = createHash('sha256').update(bytes(SOUND)).digest('hex');
  ok('regenerating the tone reproduces the exact bytes in git', before === after);
  ok('the generator is a checked-in script, not a laptop', existsSync(new URL('scripts/gen-notification-sound.mjs', root)));
}

/* -------------------------------------------------------------------------- */
/* 3. the native channels carry it                                             */
/* -------------------------------------------------------------------------- */
{
  const main = read('android/app/src/main/java/ir/fbtswap/app/MainActivity.java');
  const channels = /private void createNotificationChannels\(\)\s*\{[\s\S]*?\n  \}\n/.exec(main)?.[0] ?? '';

  ok('MainActivity creates the notification channels', channels.length > 0);
  ok('it runs on every launch, from onCreate', /createNotificationChannels\(\);/.test(main));
  ok('and only on Android 8+, where channels exist', /SDK_INT < Build\.VERSION_CODES\.O\s*\)\s*return/.test(channels));

  ok('the tone is attached to the channel by raw-resource Uri',
    /SCHEME_ANDROID_RESOURCE \+ ":\/\/".*\/raw\/" \+ SOUND_NAME/.test(channels));
  ok('the sound resource is the one that ships in res/raw',
    /SOUND_NAME = "fbt_notification"/.test(main));

  ok('ALERTS is IMPORTANCE_HIGH — that is what makes it drop in from the top',
    /CHANNEL_ALERTS,[\s\S]*?NotificationManager\.IMPORTANCE_HIGH/.test(channels));
  ok('UPDATES stays IMPORTANCE_DEFAULT — a digest must not interrupt',
    /CHANNEL_UPDATES,[\s\S]*?NotificationManager\.IMPORTANCE_DEFAULT/.test(channels));
  ok('both channels get the same tone', (channels.match(/\.setSound\(sound, audio\)/g) || []).length === 2);
  ok('audio is tagged as a notification, so it obeys the sound profile',
    /USAGE_NOTIFICATION/.test(channels) && /CONTENT_TYPE_SONIFICATION/.test(channels));
  ok('a device that refuses the channel still gets a working app',
    /catch \(Exception e\)/.test(channels));

  /* Versioned ids: the only way to ever change a sound an install already
     has a channel for. */
  ok('the channel ids are versioned, because a channel sound is permanent',
    /CHANNEL_ALERTS = "fbt_alerts_v1"/.test(main) && /CHANNEL_UPDATES = "fbt_updates_v1"/.test(main));
}

/* -------------------------------------------------------------------------- */
/* 4. FCM resolves to those channels                                           */
/* -------------------------------------------------------------------------- */
{
  const manifest = read('android/app/src/main/AndroidManifest.xml');
  ok('the manifest names the default channel, so FCM does not invent a silent one',
    /name="com\.google\.firebase\.messaging\.default_notification_channel_id"[\s\S]*?value="fbt_alerts_v1"/.test(manifest));

  const fcm = read('server/fcm.js');
  const alertsBlock = /notification: \{[\s\S]*?channelId: 'fbt_alerts_v1'/.exec(fcm)?.[0] ?? '';
  ok('a targeted alert is sent on the alert channel', alertsBlock.includes("channelId: 'fbt_alerts_v1'"));
  ok('and names our tone, not the device default', alertsBlock.includes("sound: 'fbt_notification'"));
  ok('the daily digest is sent on the quiet channel',
    /channelId: 'fbt_updates_v1'/.test(fcm));
  ok('no payload still asks for the system chime',
    !/sound: 'default'/.test(fcm));
}

/* -------------------------------------------------------------------------- */
/* 5. local notifications agree                                               */
/* -------------------------------------------------------------------------- */
{
  const notify = read('src/lib/notify.js');
  const shade = /await LocalNotifications\.schedule\(\{[\s\S]*?\n    \}\);/.exec(notify)?.[0] ?? '';
  ok('the local notification names the same channel', shade.includes("channelId: 'fbt_alerts_v1'"));
  ok('and the same tone, by base name with no extension', shade.includes("sound: 'fbt_notification'"));

  const config = JSON.parse(read('capacitor.config.json'));
  ok('the plugin default sound is ours too, for a notification that names none',
    config.plugins?.LocalNotifications?.sound === 'fbt_notification');
  ok('the plugin small icon is the monochrome brand mark',
    config.plugins?.LocalNotifications?.smallIcon === 'ic_stat_notification');
}

/* -------------------------------------------------------------------------- */
/* 6. the channel is named for the person who has to find it in Settings       */
/* -------------------------------------------------------------------------- */
{
  const values = read('android/app/src/main/res/values/strings.xml');
  const fa = read('android/app/src/main/res/values-fa/strings.xml');
  for (const key of ['notification_channel_alerts', 'notification_channel_alerts_desc',
    'notification_channel_updates', 'notification_channel_updates_desc']) {
    ok(`${key} is named`, values.includes(`name="${key}"`));
    ok(`${key} is named in Persian too — the app's own language`, fa.includes(`name="${key}"`));
  }
  ok('the Persian file is deliberately partial: the brand name stays Latin',
    !fa.includes('name="app_name"'));
}

console.log('\n✓ notification-sound-probe: all assertions passed (no device, no network)\n');
