#!/usr/bin/env python3
"""Generate the tiny, self-contained assets used by the notification renderer.

The source mask is an abstract, generated background, not financial data. The
font is the same Vazirmatn variable font shipped in public/fonts. Only the small
Latin/numeric alphabet accepted by sanitizeBannerText is rasterised. No font
parser, image decoder, system fonts or network access are needed at runtime.

Requires Pillow. Run from the repository root:
    python scripts/gen-notification-art.py
"""
from pathlib import Path
import base64
import json
import zlib

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
MASK = ROOT / 'public/notification/ambient-mask.png'
FONT = ROOT / 'public/fonts/Vazirmatn-var.woff2'
OUTPUT = ROOT / 'server/notificationArtworkAssets.js'
ALPHABET = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 .,:/+-%°$>×'

font = ImageFont.truetype(str(FONT), 192)
font.set_variation_by_axes([700])
cap_height = -font.getbbox('H', anchor='ls')[1]
font_bytes = bytearray()
glyphs = {}
for ch in ALPHABET:
    left, top, right, bottom = font.getbbox(ch, anchor='ls')
    width, height = right - left, bottom - top
    offset = len(font_bytes)
    if width and height:
        img = Image.new('L', (width, height))
        ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255, anchor='ls')
        font_bytes.extend(img.tobytes())
    glyphs[ch] = [offset, width, height, left, top, round(font.getlength(ch), 3)]

texture = Image.open(MASK).convert('L')
if texture.size != (512, 256):
    raise ValueError('ambient mask must be 512×256')

packed_font = base64.b64encode(zlib.compress(bytes(font_bytes), 9)).decode('ascii')
packed_texture = base64.b64encode(zlib.compress(texture.tobytes(), 9)).decode('ascii')
OUTPUT.write_text(
    '/** Generated by scripts/gen-notification-art.py; do not edit by hand.\n'
    ' * The font is the project\'s Vazirmatn font, rasterised to an alpha atlas.\n'
    ' * Both assets are embedded so serverless deployments need no filesystem access. */\n'
    f'export const CAP_HEIGHT = {cap_height};\n'
    f'export const GLYPHS = {json.dumps(glyphs, separators=(",", ":"), ensure_ascii=True)};\n'
    f"export const FONT_DATA = '{packed_font}';\n"
    f"export const TEXTURE_DATA = '{packed_texture}';\n",
    encoding='utf8'
)
print(f'{OUTPUT.relative_to(ROOT)}: {OUTPUT.stat().st_size:,} bytes; {len(glyphs)} glyphs')
