/**
 * TOKEN CHART — the strings for the candlestick terminal on /coin/:id.
 * ---------------------------------------------------------------------------
 * ─── WHY THIS FILE EXISTS ───────────────────────────────────────────────────
 * The professional-terminal pass added 45 keys (`coin.pro.*`, `coin.noCandles`,
 * `coin.candleNote`) to en.json and fa.json only. Every other shipped language
 * — es, fr, hi, id, pt, ru, tr, ur, zh and ar — was missing ALL of them, so
 * i18next fell back to English and a Spanish reader got a Spanish coin page
 * with an English chart toolbar, an English empty state and an English legend.
 *
 * ─── WHY IT IS GENERATED, NOT HAND-COPIED INTO TEN JSON FILES ───────────────
 * The nine partial locales are produced by scripts/gen-locales.mjs from these
 * modules (see its header: it also recomputes coverage.json, so the language
 * picker cannot claim a coverage it does not have). Adding the strings here
 * means one source of truth, no chance of a key landing in nine files and not
 * the tenth, and no hand-editing of 200 KB JSON blobs.
 *
 * ─── TRANSLATION RULES ─────────────────────────────────────────────────────
 * • Chart-standard abbreviations stay as the exchanges print them: MA, EMA,
 *   RSI, MACD, O/H/L/C, PNG. They are not words, and translating them makes
 *   the toolbar unreadable to anyone who reads charts.
 * • "BB" is "Bollinger" — an abbreviation nobody recognises is not a
 *   translation. Same for "fib" (Fibonacci).
 * • Numbers in the legend are never localised here; the legend is `dir="ltr"`
 *   and formatted by the caller so a Persian reader does not get reversed
 *   digits inside `O 3412.55`.
 * • Nothing is length-critical except the chips ("log", "fit", "reset"), which
 *   stay one short word so the toolbar does not become a second scrollable row
 *   on a 360px phone.
 */
