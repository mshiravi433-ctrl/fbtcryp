/**
 * ChartGuide — «راهنمای نمودار»: how to read the candlestick chart.
 *
 * ─── WHY THIS SCREEN EXISTS ────────────────────────────────────────────────
 * The Lab teaches the *ideas* — risk, allocation, what a drawdown feels like —
 * with smoothed line charts of its own making. The chart a reader actually
 * meets on a token page is a different object: candles, wicks, a crosshair
 * legend, eight toolbar groups, a volume pane and an AI chip. Nothing in the
 * app explained that object, so a reader who did not already know what a wick
 * means was left to infer it from the price moving.
 *
 * ─── THE RULE THAT SHAPES EVERYTHING HERE ──────────────────────────────────
 * THIS PAGE TEACHES WITH THE REAL CHART. The demo under each chapter is
 * `ProChart`, the same engine the token terminal mounts, holding a series
 * generated by `lab/marketData` — i.e. the same deterministic offline feed the
 * rest of the Lab runs on. It is NOT the live token feed, and the banner says
 * so in as many words, because a chart that looks live and is not is the one
 * dishonest thing a teaching screen could do.
 *
 * The alternative — a screenshot per step — was rejected: it cannot be in the
 * reader's language (the toolbar is drawn in the current locale), it cannot be
 * RTL, it cannot be zoomed, and it would rot the day a chip moves.
 *
 * ─── WHY THE CHAPTERS ARE DATA ─────────────────────────────────────────────
 * `chartGuideData.js` owns the curriculum, `lab2.chartGuide.*` owns every word
 * of prose, this file owns layout. That is `AppGuide`'s pattern and it is what
 * keeps eleven chapters translatable without touching JSX.
 *
 * ─── HONESTY NOTES THAT ARE PART OF THE UI, NOT THE FOOTER ─────────────────
 *   · The series is labelled «نمونهٔ آموزشی» / "practice data".
 *   · The forecast chapter says the projection is a model's opinion and that
 *     the app will tell you when it is running the baseline instead — which is
 *     what `postTokenForecast`'s `provider` field is for.
 *   · The guide never suggests a trade, a target or a "good entry".
 */
