import { CHAPTERS, CHAPTER_BY_ID, TAB_GROUPS, demoFor } from './chartGuideData';
import '../../styles/lab-chart-guide.css';

/* ── the practice series ────────────────────────────────────────────────────
 * Seeded, deterministic, and generated ONCE per session: a series that changed
 * between two chapters would make the reader think the chart was live and that
 * the lesson had moved on. The walk is deliberately calm (small drift, no
 * trends) so that a moving average or a band sits visibly around the price
 * instead of being swamped by a rally.
 */
const BARS = 160;
/* A FIXED epoch, not `Date.now()`: the series must be identical on every mount
   and in every test run, so the chart cannot appear to have "moved" between
   two chapters. One hour per bar, 160 bars ≈ 6.7 days. */
const EPOCH = Date.UTC(2024, 0, 1, 0, 0, 0);
const BAR_MS = 60 * 60 * 1000;

function makeWalk({ seed = 7, bars = BARS, start = 100 } = {}) {
  let s = seed | 0 || 1;
  const rnd = () => {
    s = (s * 1664525 + 1013904223) | 0;
    return ((s >>> 0) % 100000) / 100000;
  };
  const out = [];
  let price = start;
  for (let i = 0; i < bars; i += 1) {
    /* Two harmonics of drift + a noise term: a walk that meanders without
       either trending hard or flat-lining, which is what a teaching chart
       needs to keep a moving average meaningful. */
    const drift = Math.sin(i / 19) * 0.42 + Math.sin(i / 6.5) * 0.18;
    const noise = (rnd() - 0.5) * 1.5;
    const open = price;
    const close = Math.max(1, open + drift + noise);
    const wickUp = Math.abs(rnd() - 0.35) * 0.9;
    const wickDown = Math.abs(rnd() - 0.65) * 0.9;
    const high = Math.max(open, close) + wickUp;
    const low = Math.min(open, close) - wickDown;
    out.push({
      t: EPOCH + i * BAR_MS,
      o: +open.toFixed(2),
      h: +high.toFixed(2),
      l: +Math.max(0.5, low).toFixed(2),
      c: +close.toFixed(2),
      v: Math.round(1000 + rnd() * 4000)
    });
    price = close;
  }
  return out;
}

/* One walk for the whole session. `module` scope, not component state: two
   chapters must never draw two different "histories" of the same practice
   asset, and a StrictMode double-mount must not regenerate it. */
const PRACTICE_RAW = makeWalk();
const PRACTICE_CANDLES = toCandles(PRACTICE_RAW);

/* The demo's step chips — every control the guide teaches, each one a real
   toggle on the chart below it. Ids are the labels' key segment. */
const TOGGLES = [
  { id: 'ma7', kind: 'overlay', path: ['ma', 7], icon: 'activity' },
  { id: 'ma25', kind: 'overlay', path: ['ma', 25], icon: 'activity' },
  { id: 'ema21', kind: 'overlay', path: ['ema', 21], icon: 'activity' },
  { id: 'bb', kind: 'overlay', path: ['bb'], icon: 'gauge' },
  { id: 'volume', kind: 'pane', path: ['volume'], icon: 'layers' },
  { id: 'rsi', kind: 'pane', path: ['rsi'], icon: 'gauge' },
  { id: 'fib', kind: 'overlay', path: ['fib'], icon: 'target' }
];

const TYPE_OPTIONS = ['candles', 'line', 'area'];
const RANGE_OPTIONS = ['1D', '7D', '30D', '90D', '1Y'];

/** Read/write a nested path in an immutable state object. */
function toggledAt(obj, path) {
  const [head, ...rest] = path;
  if (!rest.length) return { ...obj, [head]: !obj?.[head] };
  return { ...obj, [head]: toggledAt(obj?.[head] ?? {}, rest) };
}

function isOn(obj, path) {
  return Boolean(path.reduce((acc, k) => acc?.[k], obj));
}

export default function ChartGuide({ onBack }) {
  const { t } = useTranslation();
  const navigate = useNavigate();
  /* `/lab/chart-guide` is its own route, so "back" is a NAVIGATION, not a state
     reset: `Lab` lives at `/lab` and this page is never mounted inside it. A
     caller that passes `onBack` (a test, or a future embedded host) wins, so
     the back affordance keeps working in both rooms. */
  const goBack = onBack ?? (() => navigate('/lab?tab=advanced'));
  const still = useStill();
  const rtl = useIsRtl();
  const chartRef = useRef(null);

  const [tabId, setTabId] = useState(TAB_GROUPS[0].id);
  const [chapterId, setChapterId] = useState(TAB_GROUPS[0].chapters[0]);
  const chapter = CHAPTER_BY_ID[chapterId] ?? CHAPTERS[0];

  /* The live demo mirrors the open chapter. `demo` is re-derived from the
     chapter id (pure), and the reader's own manual changes are applied ON TOP
     — so opening the "moving averages" chapter shows MA7+MA25 even if they had
     switched them off two chapters ago, but pressing the chip afterwards still
     works. */
  const [demo, setDemo] = useState(() => demoFor(CHAPTERS[0]));

  useEffect(() => {
    setDemo(demoFor(chapter));
  }, [chapter]);

  const [hover, setHover] = useState(null);
  const [ready, setReady] = useState(false);

  const tabs = useMemo(
    () => TAB_GROUPS.map((g) => ({ id: g.id, label: t(`lab2.chartGuide.tabs.${g.id}`) })),
    [t]
  );
  const chaptersInTab = TAB_GROUPS.find((g) => g.id === tabId)?.chapters ?? [];

  const pickTab = (id) => {
    if (id === tabId) return;
    const first = TAB_GROUPS.find((g) => g.id === id)?.chapters[0];
    setTabId(id);
    if (first) setChapterId(first);
  };

  /* ONE fixed series, 160 one-hour bars from a pinned epoch. The demo has no
     range chips of its own: the token page owns those, and a second range
     control here would either lie (the practice walk is not date-indexed) or
     disagree with the real one. What the demo does reproduce is the toolbar's
     STATE — type, overlays, panes, scale — which is what the chapters teach. */
  const candles = PRACTICE_CANDLES;
  const volume = useMemo(
    () => candles.map((c, i) => ({ t: c.time, v: PRACTICE_RAW[i]?.v ?? 0 })),
    [candles]
  );

  const applyToggle = (item) => {
    setDemo((d) =>
      item.kind === 'overlay'
        ? { ...d, overlays: toggledAt(d.overlays, item.path) }
        : { ...d, panes: toggledAt(d.panes, item.path) }
    );
  };

  const bar = hover ?? null;

  return (
    <div className="lab2-screen lab2-cg acc-cyan">
      <LabBack
        onBack={goBack}
        icon="activity"
        accent="cyan"
        title={t('lab2.screens.chartGuide.title')}
        sub={t('lab2.screens.chartGuide.sub')}
      />

      {/* ─── THE HONESTY BANNER, BEFORE ANY PIXELS OF CHART ────────────────
          A reader who scrolled past a disclaimer under the chart would think
          the chart was the real BTC price. It is not, so the sentence comes
          first and is part of the chrome, not a footnote. */}
      <div className="lab2-cg-sample" data-testid="chart-guide-sample">
        <LabIcon name="flask" width={14} height={14} />
        <span>{t('lab2.chartGuide.sampleData')}</span>
      </div>

      <LabChips items={tabs} value={tabId} onChange={pickTab} layoutId="cg-tab" accent="cyan" />

      <div className="lab2-cg-chapters" role="group" aria-label={t('lab2.chartGuide.chaptersLabel')}>
        {chaptersInTab.map((id) => {
          const c = CHAPTER_BY_ID[id];
          const on = id === chapterId;
          return (
            <button
              key={id}
              type="button"
              className={`lab2-cg-chapter acc-${c.accent} ${on ? 'on' : ''}`}
              aria-pressed={on}
              onClick={() => setChapterId(id)}
              data-testid={`chart-guide-chapter-${id}`}
            >
              <span className="lab2-cg-chapter-icon" aria-hidden="true">
                <LabIcon name={c.icon} width={15} height={15} />
              </span>
              <span className="lab2-cg-chapter-title">{t(`lab2.chartGuide.chapters.${id}.title`)}</span>
              {on && !still && (
                <motion.span
                  layoutId="cg-chapter-pill"
                  className="lab2-cg-chapter-pill"
                  transition={{ type: 'spring', stiffness: 420, damping: 36 }}
                />
              )}
            </button>
          );
        })}
      </div>

      {/* ─── THE LIVE DEMO ───────────────────────────────────────────────── */}
      <Panel
        title={t('lab2.chartGuide.demo.title')}
        icon="activity"
        accent="cyan"
        action={(
          <span className="lab2-cg-demo-badge" aria-hidden="true">
            {t(`lab2.chartGuide.chapters.${chapter.id}.title`)}
          </span>
        )}
      >
        <div className="lab2-cg-legend" dir="ltr" aria-live="off">
          {bar ? (
            <>
              <span><em>{t('coin.pro.o')}</em>{bar.open.toFixed(2)}</span>
              <span><em>{t('coin.pro.h')}</em>{bar.high.toFixed(2)}</span>
              <span><em>{t('coin.pro.l')}</em>{bar.low.toFixed(2)}</span>
              <span><em>{t('coin.pro.c')}</em>{bar.close.toFixed(2)}</span>
            </>
          ) : (
            <span className="lab2-cg-legend-hint">{t('lab2.chartGuide.demo.legendHint')}</span>
          )}
        </div>

        <div className="lab2-cg-chart">
          <ProChart
            ref={chartRef}
            candles={candles}
            volume={demo.panes.volume ? volume : []}
            chartType={demo.chartType}
            overlays={demo.overlays}
            settings={demo.settings}
            rsiOn={demo.panes.rsi}
            locale={rtl ? 'fa' : 'en'}
            showPriceLine={demo.showPriceLine}
            onCrosshair={setHover}
            onReady={() => setReady(true)}
            fallbackHeight={210}
            dataKey={`guide-${chapter.id}`}
          />
        </div>

        <div className="lab2-cg-controls">
          <div className="lab2-cg-control-row">
            <span className="lab2-cg-control-label">{t('lab2.chartGuide.demo.type')}</span>
            <div className="lab2-cg-chips">
              {TYPE_OPTIONS.map((id) => (
                <button
                  key={id}
                  type="button"
                  className={`lab2-cg-chip ${demo.chartType === id ? 'on' : ''}`}
                  aria-pressed={demo.chartType === id}
                  onClick={() => {
                    setDemo((d) => ({ ...d, chartType: id }));
                  }}
                >
                  {t(`lab2.chartGuide.demo.types.${id}`)}
                </button>
              ))}
            </div>
          </div>

          <div className="lab2-cg-control-row">
            <span className="lab2-cg-control-label">{t('lab2.chartGuide.demo.toggles')}</span>
            <div className="lab2-cg-chips">
              {TOGGLES.map((item) => {
                const on = isOn(item.kind === 'overlay' ? demo.overlays : demo.panes, item.path);
                return (
                  <button
                    key={item.id}
                    type="button"
                    className={`lab2-cg-chip ${on ? 'on' : ''}`}
                    aria-pressed={on}
                    onClick={() => applyToggle(item)}
                    data-testid={`chart-guide-toggle-${item.id}`}
                  >
                    <LabIcon name={item.icon} width={12} height={12} />
                    {t(`lab2.chartGuide.demo.togglesMap.${item.id}`)}
                  </button>
                );
              })}
            </div>
          </div>

          <div className="lab2-cg-control-row">
            <span className="lab2-cg-control-label">{t('lab2.chartGuide.demo.view')}</span>
            <div className="lab2-cg-chips">
              <button
                type="button"
                className="lab2-cg-chip"
                onClick={() => chartRef.current?.zoom(0.6)}
                disabled={!ready}
              >
                {t('lab2.chartGuide.demo.zoomIn')}
              </button>
              <button
                type="button"
                className="lab2-cg-chip"
                onClick={() => chartRef.current?.fit()}
                disabled={!ready}
              >
                {t('lab2.chartGuide.demo.fit')}
              </button>
              <button
                type="button"
                className={`lab2-cg-chip ${demo.settings.log ? 'on' : ''}`}
                aria-pressed={Boolean(demo.settings.log)}
                onClick={() => {
                  setDemo((d) => ({ ...d, settings: { ...d.settings, log: !d.settings.log } }));
                }}
              >
                {t('lab2.chartGuide.demo.log')}
              </button>
            </div>
          </div>
          {!ready && (
            <p className="lab2-cg-note">{t('lab2.chartGuide.demo.loadingNote')}</p>
          )}
        </div>
      </Panel>

      {/* ─── THE STEPS ───────────────────────────────────────────────────── */}
      <motion.ol
        className="lab2-cg-steps"
        key={chapter.id}
        initial={still ? false : { opacity: 0, y: 10 }}
        animate={{ opacity: 1, y: 0 }}
        transition={{ duration: 0.32, ease: LAB_EASE }}
      >
        {chapter.steps.map((stepId, i) => (
          <motion.li
            key={stepId}
            className="lab2-cg-step"
            initial={still ? false : { opacity: 0, y: 12 }}
            animate={{ opacity: 1, y: 0 }}
            transition={{ duration: 0.3, ease: LAB_EASE, delay: still ? 0 : Math.min(i * 0.05, 0.3) }}
          >
            <span className="lab2-cg-step-num lab2-num" aria-hidden="true">{i + 1}</span>
            <div className="lab2-cg-step-body">
              <div className="lab2-cg-step-title">
                {t(`lab2.chartGuide.chapters.${chapter.id}.steps.${stepId}.title`)}
              </div>
              <p className="lab2-cg-step-text">
                {t(`lab2.chartGuide.chapters.${chapter.id}.steps.${stepId}.body`)}
              </p>
              {/* The `where` line is what makes this guide usable on the real
                  screen: it names the room and the chip, in the same words the
                  toolbar uses. */}
              <div className="lab2-cg-step-where">
                <LabIcon name="target" width={12} height={12} />
                <span>{t(`lab2.chartGuide.chapters.${chapter.id}.steps.${stepId}.where`)}</span>
              </div>
            </div>
          </motion.li>
        ))}
      </motion.ol>

      <Notice variant="tip" icon="bulb" title={t('lab2.chartGuide.noteTitle')}>
        {t('lab2.chartGuide.note')}
      </Notice>

      <div className="lab2-cg-exit">
        <Link className="lab2-btn primary full" to="/lab?tab=practice">
          <LabIcon name="next" width={15} height={15} />
          <span>{t('lab2.chartGuide.backToLab')}</span>
        </Link>
      </div>
    </div>
  );
}
