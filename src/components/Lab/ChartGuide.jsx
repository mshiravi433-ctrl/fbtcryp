import { useTranslation } from 'react-i18next';
import { Link, useNavigate } from 'react-router-dom';
import { motion } from 'framer-motion';
import {
  LAB_EASE,
  LabBack,
  LabChips,
  Notice,
  Panel,
  useIsRtl
} from './Shared';
import { LabIcon } from './LabIcons';
